// Controle structurel YAML et garde-fous, distinct de la validation des regles.
import assert from 'node:assert/strict';
import { readFile, realpath } from 'node:fs/promises';
import { resolve } from 'node:path';
import { execFileSync } from 'node:child_process';
import { parseDocument } from 'yaml';

const root = resolve(import.meta.dirname, '../..');
const read = path => readFile(resolve(root, path), 'utf8');
const source = await read('.github/workflows/firestore-security-manual.yml');
const parsed = parseDocument(source, { uniqueKeys: true });
assert.equal(parsed.errors.length, 0, parsed.errors.map(e => e.message).join('\n'));
const workflow = parsed.toJS();
assert.deepEqual(Object.keys(workflow.on).sort(), ['push', 'workflow_dispatch']);
assert.deepEqual(workflow.on.push, { branches: ['developpement-coach'] });
assert.deepEqual(workflow.permissions, { contents: 'read' });
assert.deepEqual(Object.keys(workflow.jobs), ['verify']);
const job = workflow.jobs.verify;
assert.equal(job['runs-on'], 'ubuntu-24.04');
assert.equal(job['timeout-minutes'], 25);
assert.equal(execFileSync('git', ['branch', '--show-current'], { cwd: root, encoding: 'utf8' }).trim(), 'developpement-coach');
assert.ok(!/secrets\.|firebase\s+(deploy|login|use)|GOOGLE_APPLICATION_CREDENTIALS|FIREBASE_TOKEN|pull_request_target/.test(source));
assert.ok(source.includes('test "$GITHUB_REF" = refs/heads/developpement-coach'));
assert.ok(source.includes('push|workflow_dispatch) ;;'));
assert.ok(!/actions\/(deploy-pages|configure-pages|upload-pages-artifact)@/.test(source));
const checkout = job.steps.find(step => step.uses?.startsWith('actions/checkout@'));
assert.equal(checkout.with['persist-credentials'], false);
assert.equal(job.steps.find(step => step.uses?.startsWith('actions/setup-node@')).with['node-version'], '24');
assert.equal(job.steps.find(step => step.uses?.startsWith('actions/setup-java@')).with['java-version'], '21');
const engine = job.steps.find(step => step.id === 'firestore');
assert.ok(engine.run.includes('--project demo-objectif-5-tractions'));
assert.ok(engine.run.includes('--only firestore'));
assert.ok(engine.run.includes('--config firestore/firebase.json'));
assert.ok(engine.run.includes('--test-concurrency=1'));
assert.ok(engine.run.includes('set -o pipefail'));
assert.ok(!job.steps.some(step => step['continue-on-error']));
const config = JSON.parse(await read('tests/firestore/firebase.json'));
assert.equal(config.emulators.firestore.host, '127.0.0.1');
assert.equal(config.emulators.firestore.port, 8080);
assert.equal(await realpath(resolve(root, 'tests/firestore', config.firestore.rules)), await realpath(resolve(root, 'firebase/firestore.rules')));
const tests = await read('tests/firestore/security.test.mjs');
assert.equal((tests.match(/^test\('/gm) || []).length, 24);
assert.ok(tests.includes("process.env.FIRESTORE_EMULATOR_HOST !== '127.0.0.1:8080'"));
const manifest = JSON.parse(await read('tests/package.json'));
assert.equal(manifest.private, true);
assert.ok(Object.values(manifest.devDependencies).every(value => /^\d+\.\d+\.\d+$/.test(value)));
const [major, minor] = process.versions.node.split('.').map(Number);
assert.ok(major > 24 || (major === 24 && minor >= 12), 'Node >=24.12.0 requis');
console.log('PASS YAML parse et cles uniques, push developpement uniquement, manuel conserve, permissions, versions, projet demo, chemins et 24 scenarios.');
console.log('Ce controle ne compile pas les regles et ne prouve pas la securite.');
